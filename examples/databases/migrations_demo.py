"""Alembic: міграція з даними (expand → contract), що бачить і чого не бачить autogenerate,
NOT NULL на таблиці з рядками, `alembic check`, дві голови.

    python migrations_demo.py                      # SQLite у тимчасовій папці
    DATABASE_URL=postgresql+asyncpg://postgres:x@localhost:5544/postgres python migrations_demo.py

На PostgreSQL скрипт видаляє таблиці news і alembic_version у базі з DATABASE_URL — бери тимчасову базу.
"""
import asyncio
import logging
import os
import shutil
import tempfile
from pathlib import Path

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.operations import Operations
from alembic.util.exc import AutogenerateDiffsDetected, CommandError
from sqlalchemy import CheckConstraint, Column, Integer, MetaData, String, Table, text
from sqlalchemy.ext.asyncio import create_async_engine

HERE = Path(__file__).parent
os.environ.setdefault("DATABASE_URL", f"sqlite+aiosqlite:///{tempfile.mkdtemp()}/migrations.db")
URL = os.environ["DATABASE_URL"]


def config(script_location: Path = HERE / "migrations_demo") -> Config:
    cfg = Config(str(HERE / "migrations_demo" / "alembic.ini"))
    cfg.set_main_option("script_location", str(script_location))
    return cfg


def run(sql: str, *, fetch: bool = False) -> list[tuple] | None:
    async def go() -> list[tuple] | None:
        engine = create_async_engine(URL)
        async with engine.begin() as conn:
            result = await conn.execute(text(sql))
            rows = [tuple(r) for r in result] if fetch else None
        await engine.dispose()
        return rows
    return asyncio.run(go())


def diff(metadata: MetaData) -> list:
    """Те саме порівняння, що робить `alembic revision --autogenerate`: модель проти бази."""
    async def go() -> list:
        engine = create_async_engine(URL)
        async with engine.connect() as conn:
            result = await conn.run_sync(lambda sync: compare_metadata(MigrationContext.configure(sync), metadata))
        await engine.dispose()
        return result
    return asyncio.run(go())


def news_table(*columns: Column, **kw: object) -> MetaData:
    metadata = MetaData()
    Table("news", metadata, Column("id", Integer, primary_key=True), *columns, **kw)
    return metadata


def short(op: object) -> str:
    if isinstance(op, list):                                   # modify_* приходять списком
        op = op[0]
    kind, *rest = op
    target = next((x for x in rest if hasattr(x, "name") and not isinstance(x, str)), None)
    if kind in ("modify_nullable", "modify_type", "modify_default"):
        return f"{kind} {rest[1]}.{rest[2]}"
    return f"{kind} {getattr(target, 'name', rest[:2])}"


def main() -> None:
    print("база:", URL.split(":")[0])
    run("DROP TABLE IF EXISTS news")
    run("DROP TABLE IF EXISTS alembic_version")

    print("--- 1. 0001, дані старої версії застосунку, потім 0002 (expand + data migration)")
    command.upgrade(config(), "0001")
    run("INSERT INTO news (url, title) VALUES ('https://example.com/economy/1', 'Гривня зміцнилася'), "
        "('https://example.com/society/2', 'Нові поїзди')")
    command.upgrade(config(), "0002")
    run("INSERT INTO news (url, title) VALUES ('https://example.com/3', 'Стара версія ще працює')")
    print("    після 0002:", run("SELECT id, category FROM news ORDER BY id", fetch=True))
    command.upgrade(config(), "head")
    print("    після head:", run("SELECT id, category FROM news ORDER BY id", fetch=True))
    command.current(config())

    print("--- 2. alembic check: модель і база збігаються?")
    command.check(config())
    from migrations_demo.models import News
    extra = Column("summary", String(300))
    News.__table__.append_column(extra)                        # «забули» написати міграцію
    try:
        command.check(config())
    except AutogenerateDiffsDetected as exc:
        print("    AutogenerateDiffsDetected:", str(exc).splitlines()[0][:110])
    News.__table__._columns.remove(extra)

    print("--- 3. що бачить autogenerate (модель проти бази на head)")
    def base() -> list[Column]:
        return [Column("url", String(500), nullable=False, unique=True),
                Column("title", String(300), nullable=False, index=True),
                Column("category", String(100), nullable=False)]

    cases = {
        "перейменували title → headline": news_table(base()[0], Column("headline", String(300), nullable=False, index=True), base()[2]),
        "String(100) → String(200)": news_table(*base()[:2], Column("category", String(200), nullable=False)),
        "nullable=False → True": news_table(*base()[:2], Column("category", String(100), nullable=True)),
        "додали server_default": news_table(*base()[:2], Column("category", String(100), nullable=False,
                                                                 server_default="Новини")),
        "додали CHECK": news_table(*base(), CheckConstraint("length(title) > 5", name="title_len")),
        "перейменували таблицю": MetaData(),
    }
    Table("articles", cases["перейменували таблицю"], Column("id", Integer, primary_key=True), *base())
    logging.getLogger("alembic").setLevel(logging.WARNING)       # лише підсумок, без INFO на кожну зміну
    for title, metadata in cases.items():
        found = [short(op) for op in diff(metadata) if short(op) != "remove_table alembic_version"]
        print(f"    {title:32} → {found or 'нічого не знайдено'}")

    logging.getLogger("alembic").setLevel(logging.INFO)

    print("--- 4. NOT NULL одразу, на таблиці з рядками")

    async def add_not_null() -> None:
        engine = create_async_engine(URL)
        async with engine.begin() as conn:
            await conn.run_sync(lambda sync: Operations(MigrationContext.configure(sync)).add_column(
                "news", Column("source", String(100), nullable=False)))
        await engine.dispose()
    try:
        asyncio.run(add_not_null())
    except Exception as exc:  # noqa: BLE001 — показуємо помилку бази
        print("   ", type(exc).__name__ + ":", str(getattr(exc, "orig", exc)).splitlines()[0].split(") ")[-1][:110])

    print("--- 5. дві гілки з однаковим down_revision")
    copy = Path(tempfile.mkdtemp()) / "migrations"
    shutil.copytree(HERE / "migrations_demo", copy, ignore=shutil.ignore_patterns("__pycache__"))
    cfg = config(copy)
    cfg.attributes["configure_logger"] = False
    command.revision(cfg, "a: summary column", rev_id="0005a", head="0004")
    command.revision(cfg, "b: views column", rev_id="0005b", head="0004", splice=True)
    command.heads(cfg)
    try:
        command.upgrade(cfg, "head")
    except CommandError as exc:
        print("    CommandError:", str(exc)[:110])
    command.merge(cfg, "heads", message="merge a and b", rev_id="0006")
    command.upgrade(cfg, "head")
    command.current(cfg)

    print("--- 6. downgrade до 0001: дані category втрачено")
    command.downgrade(cfg, "0001")
    print("    стовпці:", [r[1] for r in run("PRAGMA table_info(news)", fetch=True)] if URL.startswith("sqlite")
          else run("SELECT column_name FROM information_schema.columns WHERE table_name = 'news' "
                   "ORDER BY ordinal_position", fetch=True))

    if not URL.startswith("postgresql"):
        return
    print("--- 7. ALTER TABLE за довгим запитом: lock_timeout (PostgreSQL)")

    async def blocked_alter() -> None:
        engine = create_async_engine(URL)
        async with engine.connect() as reader, engine.connect() as migration:
            await reader.execute(text("BEGIN"))
            await reader.execute(text("SELECT count(*) FROM news"))      # звіт тримає ACCESS SHARE
            await migration.execute(text("SET lock_timeout = '1s'"))
            started = asyncio.get_running_loop().time()
            try:
                await migration.execute(text("ALTER TABLE news ADD COLUMN source varchar(100)"))
            except Exception as exc:  # noqa: BLE001 — показуємо помилку бази
                waited = asyncio.get_running_loop().time() - started
                message = str(getattr(exc, "orig", exc)).splitlines()[0].split(") ")[-1]
                print(f"    через {waited:.1f} с: {type(exc).__name__}: {message[:90]}")
            await reader.execute(text("ROLLBACK"))
        await engine.dispose()
    asyncio.run(blocked_alter())


if __name__ == "__main__":
    main()
